static inline int32_t pabsh(int32_t v) {
    int32_t out;
    asm (
        "pabsh %0, %1"
        : "=r"(out)
        : "r"(v)
    );
    return out;
}

static inline int32_t psahx(int32_t v) {
    int32_t out;
    asm (
        "psahx %0, %1, %1"
        : "=r"(out)
        : "r"(v)
    );
    return out;
}

static inline int32_t pclipuh(int32_t v, unsigned imm) {
    int32_t out;
    asm (
        "pclipuh %0, %1, %2"
        : "=r"(out)
        : "r"(v), "I"(imm)
    );
    return out;
}

