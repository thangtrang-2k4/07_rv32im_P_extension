static inline int abs_int(int v) { return v < 0 ? -v : v; }

// 3×3 Sobel kernels 
static const int8_t KX0[3] = { -1,  0, +1 };   // row y–1
static const int8_t KX1[3] = { -2,  0, +2 };   // row  y
static const int8_t KX2[3] = { -1,  0, +1 };   // row y+1

static const int8_t KY0[3] = { +1, +2, +1 };   // row y–1
static const int8_t KY1[3] = {  0,  0,  0 };   // row  y  (unused)
static const int8_t KY2[3] = { -1, -2, -1 };   // row y+1

/* --------------------------------------------------------------
 *  sobel_scalar_basic()
 *  computes one output pixel per inner iteration
 * ------------------------------------------------------------ */
void sobel_scalar_basic(const uint8_t * restrict src,
                        uint8_t       * restrict dst,
                        int width, int height)
{
    for (int y = 1; y < height - 1; ++y) {
        const uint8_t *r0 = src + (y - 1) * width;
        const uint8_t *r1 = src +  y      * width;
        const uint8_t *r2 = src + (y + 1) * width;
              uint8_t *d  = dst +  y      * width;

        for (int x = 1; x < width - 1; ++x) {
            /* horizontal gradient */
            int gx =
                KX0[0]*r0[x-1] + KX0[1]*r0[x]   + KX0[2]*r0[x+1] +
                KX1[0]*r1[x-1] /*+ KX1[1]*r1[x]*/ + KX1[2]*r1[x+1] +
                KX2[0]*r2[x-1] + KX2[1]*r2[x]   + KX2[2]*r2[x+1];

            /* vertical gradient */
            int gy =
                KY0[0]*r0[x-1] + KY0[1]*r0[x]   + KY0[2]*r0[x+1] +
                KY2[0]*r2[x-1] + KY2[1]*r2[x]   + KY2[2]*r2[x+1];

            /* magnitude and clamp */
            int mag = abs_int(gx) + abs_int(gy);
            d[x] = (uint8_t)(mag > 255 ? 255 : mag);
        }
    }
}

static inline uint32_t load32u(const void *p)
{
    uint32_t v;
    __builtin_memcpy(&v, p, 4);
    return v;
}

/* =============================================================== */
/*  SIMD + P‑extension implementation                              */
/* =============================================================== */
void sobel_simd(const uint8_t * restrict src,
                uint8_t       * restrict dst,
                int width, int height)
{


  // Gx row y‑1: [ -1,  0, +1 ]
  const int32_t KX0 = 0x000100FF;  // bytes: FF 00 01 00 → { -1, 0, +1, 0 }

  // Gx row y  : [ -2,  0, +2 ]
  const int32_t KX1 = 0x000200FE;  // bytes: FE 00 02 00 → { -2, 0, +2, 0 }

  // Gx row y+1: same as row y‑1
  const int32_t KX2 = 0x000100FF;  // bytes: FF 00 01 00 → { -1, 0, +1, 0 }

  // Gy row y‑1: [ +1, +2, +1 ]
  const int32_t KY0 = 0x00010201;  // bytes: 01 02 01 00 → { +1, +2, +1, 0 }

  // Middle row for sobel y kernel is 0. 

  // Gy row y+1: [ -1, -2, -1 ]
  const int32_t KY2 = 0x00FFFEFF;  // bytes: FF FE FF 00 → { -1, -2, -1, 0 }

for (int y = 1; y < height - 1; ++y) {
    const uint8_t *r0 = src + (y - 1)*width;
    const uint8_t *r1 = src +  y   *width;
    const uint8_t *r2 = src + (y + 1)*width;
          uint8_t *d  = dst +  y   *width;

    // seed the sliding windows at x=1
    uint32_t W0 = load32u(r0 + 0);
    uint32_t W1 = load32u(r1 + 0);
    uint32_t W2 = load32u(r2 + 0);

    for (int x = 1; x < width - 1; ++x) {
        int32_t gx = 0, gy = 0;
        gx = smaqasu(gx, KX0, W0);
        gx = smaqasu(gx, KX1, W1);
        gx = smaqasu(gx, KX2, W2);

        gy = smaqasu(gy, KY0, W0);
        gy = smaqasu(gy, KY2, W2);

        int32_t gxy = (gy << 16) | (uint16_t)gx;
        gxy = pabsh(gxy);
        gxy = psahx(gxy);
        gxy = pclipuh(gxy, 8);
        d[x] = (uint8_t)gxy;

        // slide each window right by one byte and pull in the new pixel
        // that sits at index x+2
        W0 = (W0 >>  8) | ((uint32_t)r0[x+3] << 24);
        W1 = (W1 >>  8) | ((uint32_t)r1[x+3] << 24);
        W2 = (W2 >>  8) | ((uint32_t)r2[x+3] << 24);
    }
}
}
