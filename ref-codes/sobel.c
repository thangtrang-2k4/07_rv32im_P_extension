/* =============================================================== 
   Inline‑asm wrappers for P‑extension instructions              
   =============================================================== */
static inline int32_t smaqasu(int32_t accum, int32_t a, uint32_t b)
{
    asm volatile (
        "smaqasu %0, %1, %2\n"
        : "+r"(accum)      // accum is read+written in the same register
        : "r"(a), "r"(b)   // a is signed lanes, b is unsigned lanes
    );
    return accum;
}
